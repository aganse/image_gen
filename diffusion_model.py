"""Denoising diffusion model built from Hugging Face `diffusers` components.

A diffusion model (Ho et al. 2020, "DDPM") is trained to undo a gradual
noising process: take a training image, add a random amount of Gaussian noise
(indexed by a timestep t), and train a network to predict that noise.  New
images are generated by starting from pure noise and iteratively denoising.

Rather than re-implement the standard pieces, this module wraps the de-facto
standard implementations from `diffusers`:

    denoiser          diffusers.UNet2DModel        (hf_model_class)
    training noise    diffusers.DDPMScheduler      (train_scheduler_class)
    sampler           diffusers.DDIMScheduler      (sample_scheduler_class)

Each is selected *by class name* from the params file and built from a config
dict, so other diffusers classes can be swapped in without code changes - for
example a different sampler ("DPMSolverMultistepScheduler"), or a pretrained
denoiser via hf_pretrained.  build_hf_component() is the single lookup point
and works for any diffusers class (e.g. "AutoencoderKL").

Constraint on swapped-in denoisers: they must be callable as
`model(noisy_images, timesteps).sample` (true for UNet2DModel and other
unconditional image denoisers in diffusers).

Classes / functions:
    build_hf_component   construct any diffusers model/scheduler by name
    DiffusionLitModule   LightningModule with DDPM training + sampling
"""

import diffusers
import torch
import torch.nn.functional as F

from gen_base import (
    EMAModel,
    GenerativeLitModule,
    chw_from_image_shape,
    initial_learning_rate,
    optimizer_config,
)

# A reasonable 64x64 denoiser for a single 16GB GPU: four resolution levels
# (64, 32, 16, 8) with self-attention at 16x16.  For 128x128 images add a
# level, e.g. block_out_channels [128, 128, 256, 256, 512] with one more
# "DownBlock2D"/"UpBlock2D" at the start/end of the block-type lists.
DEFAULT_UNET_CONFIG = {
    "layers_per_block": 2,
    "block_out_channels": [128, 128, 256, 256],
    "down_block_types": [
        "DownBlock2D", "DownBlock2D", "AttnDownBlock2D", "DownBlock2D",
    ],
    "up_block_types": [
        "UpBlock2D", "AttnUpBlock2D", "UpBlock2D", "UpBlock2D",
    ],
}

DEFAULT_TRAIN_SCHEDULER_CONFIG = {
    "num_train_timesteps": 1000,
    "beta_schedule": "linear",
    "prediction_type": "epsilon",
}


def build_hf_component(class_name, config=None, pretrained=None):
    """Instantiate a diffusers model or scheduler class by name.

    class_name: name of any class exported by `diffusers`, e.g. "UNet2DModel",
        "AutoencoderKL", "DDPMScheduler", "DDIMScheduler".
    config: dict of constructor kwargs (ignored when pretrained is given).
    pretrained: optional Hugging Face Hub id or local directory to load with
        `from_pretrained`.  Note cloud training jobs in this repo run in a
        private subnet with no internet access, so a Hub id only works if
        the weights were baked into the Docker image (or are on local disk).
    """
    cls = getattr(diffusers, str(class_name), None)
    if cls is None:
        raise ValueError(f"diffusers has no class named {class_name!r}.")
    if pretrained:
        return cls.from_pretrained(pretrained)
    return cls(**dict(config or {}))


class DiffusionLitModule(GenerativeLitModule):
    """LightningModule for unconditional pixel-space diffusion.

    Architecture args (image_shape, hf_model_class, hf_model_config,
    hf_pretrained, train_scheduler_class, train_scheduler_config,
    sample_scheduler_class, num_inference_steps) come from model_arch_params;
    the rest from training_params.

    Sampling uses an EMA copy of the denoiser (ema_decay > 0) and by default a
    deterministic DDIM sampler with num_inference_steps steps, which is ~20x
    cheaper than the 1000-step DDPM ancestral sampler for similar quality.
    """

    def __init__(
        self,
        image_shape=(64, 64, 3),
        hf_model_class="UNet2DModel",
        hf_model_config=None,
        hf_pretrained=None,
        train_scheduler_class="DDPMScheduler",
        train_scheduler_config=None,
        sample_scheduler_class="DDIMScheduler",
        num_inference_steps=50,
        learning_rate=1e-4,
        weight_decay=0.0,
        ema_decay=0.9999,
    ):
        super().__init__()
        channels, height, width = chw_from_image_shape(image_shape)
        self.image_chw = (channels, height, width)

        model_config = dict(
            DEFAULT_UNET_CONFIG if hf_model_config is None else hf_model_config
        )
        if not hf_pretrained:
            # Image size/channels follow image_shape unless set explicitly.
            model_config.setdefault(
                "sample_size", height if height == width else [height, width]
            )
            model_config.setdefault("in_channels", channels)
            model_config.setdefault("out_channels", channels)
        self.denoiser = build_hf_component(
            hf_model_class, model_config, pretrained=hf_pretrained
        )
        self.train_scheduler = build_hf_component(
            train_scheduler_class,
            DEFAULT_TRAIN_SCHEDULER_CONFIG
            if train_scheduler_config is None else train_scheduler_config,
        )
        # Validate the sampler class name now rather than at first sampling.
        if getattr(diffusers, str(sample_scheduler_class), None) is None:
            raise ValueError(
                f"diffusers has no class named {sample_scheduler_class!r}."
            )
        self.sample_scheduler_class = sample_scheduler_class
        self.num_inference_steps = int(num_inference_steps)
        self.ema = (
            EMAModel(self.denoiser, decay=ema_decay)
            if ema_decay and ema_decay > 0 else None
        )
        self.learning_rate = learning_rate
        self.weight_decay = float(weight_decay)

    def forward(self, noisy_images, timesteps):
        return self.denoiser(noisy_images, timesteps).sample

    def training_step(self, batch, batch_idx):
        x = batch
        noise = torch.randn_like(x)
        timesteps = torch.randint(
            0,
            self.train_scheduler.config.num_train_timesteps,
            (x.size(0),),
            device=x.device,
            dtype=torch.long,
        )
        noisy = self.train_scheduler.add_noise(x, noise, timesteps)
        prediction = self.denoiser(noisy, timesteps).sample

        prediction_type = self.train_scheduler.config.prediction_type
        if prediction_type == "epsilon":
            target = noise
        elif prediction_type == "v_prediction":
            target = self.train_scheduler.get_velocity(x, noise, timesteps)
        elif prediction_type == "sample":
            target = x
        else:
            raise ValueError(f"Unsupported prediction_type {prediction_type!r}.")

        loss = F.mse_loss(prediction, target)
        self.log(
            "loss", loss, prog_bar=True,
            on_step=False, on_epoch=True, batch_size=x.size(0),
        )
        return loss

    def on_train_batch_end(self, outputs, batch, batch_idx):
        # Called after the optimizer step, so the EMA sees the updated weights.
        if self.ema is not None:
            self.ema.update(self.denoiser)

    def configure_optimizers(self):
        optimizer = torch.optim.AdamW(
            self.denoiser.parameters(),
            lr=initial_learning_rate(self.learning_rate),
            weight_decay=self.weight_decay,
        )
        return optimizer_config(optimizer, self.learning_rate)

    # -- sampling interface -------------------------------------------------

    def make_noise(self, n, generator=None):
        return torch.randn(n, *self.image_chw, generator=generator)

    def sample_from_noise(self, noise):
        """Run the reverse (denoising) process starting from `noise`."""
        scheduler_cls = getattr(diffusers, self.sample_scheduler_class)
        scheduler = scheduler_cls.from_config(self.train_scheduler.config)
        scheduler.set_timesteps(self.num_inference_steps)
        net = self.ema.ema_model if self.ema is not None else self.denoiser

        x = noise * scheduler.init_noise_sigma
        for t in scheduler.timesteps:
            model_input = scheduler.scale_model_input(x, t)
            model_output = net(model_input, t).sample
            x = scheduler.step(model_output, t, x).prev_sample
        return x
