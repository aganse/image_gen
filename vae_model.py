"""Convolutional variational autoencoder (VAE) for image generation.

A VAE (Kingma & Welling 2014) pairs an encoder q(z|x), mapping an image to a
Gaussian in a low-dimensional latent space, with a decoder p(x|z) mapping
latent points back to images.  Training maximizes the evidence lower bound:

    loss = reconstruction_error(x, decode(z)) + kl_weight * KL(q(z|x) || N(0,I))

After training, new images are generated by decoding z ~ N(0, I).  VAEs train
stably and cover the data distribution well, but their samples are typically
blurrier than GAN or diffusion samples - a useful baseline for comparison.

Classes:
    ConvVAE       plain torch.nn.Module with the encoder/decoder networks
    VAELitModule  LightningModule wrapping ConvVAE with loss + optimizer
"""

import torch
import torch.nn as nn
import torch.nn.functional as F

from gen_base import (
    GenerativeLitModule,
    chw_from_image_shape,
    initial_learning_rate,
    optimizer_config,
)


class ConvVAE(nn.Module):
    """Strided-convolution encoder and transposed-convolution decoder.

    Each entry of channel_mults adds one stride-2 stage, so the encoder ends
    at spatial size (H / 2^n, W / 2^n) with base_channels * channel_mults[-1]
    feature maps.  For 64x64 images the default (1, 2, 4, 8) ends at 4x4.
    """

    def __init__(
        self,
        image_shape=(64, 64, 3),
        latent_dim=128,
        base_channels=64,
        channel_mults=(1, 2, 4, 8),
    ):
        super().__init__()
        channels, height, width = chw_from_image_shape(image_shape)
        n_stages = len(channel_mults)
        factor = 2 ** n_stages
        if height % factor or width % factor:
            raise ValueError(
                f"Image size {height}x{width} must be divisible by {factor} "
                f"for {n_stages} downsampling stages."
            )
        self.latent_dim = int(latent_dim)
        widths = [int(base_channels * m) for m in channel_mults]
        self.feature_shape = (widths[-1], height // factor, width // factor)
        n_features = widths[-1] * (height // factor) * (width // factor)

        encoder_layers = []
        in_ch = channels
        for out_ch in widths:
            encoder_layers += [
                nn.Conv2d(in_ch, out_ch, kernel_size=4, stride=2, padding=1),
                nn.BatchNorm2d(out_ch),
                nn.LeakyReLU(0.2, inplace=True),
            ]
            in_ch = out_ch
        self.encoder = nn.Sequential(*encoder_layers)
        self.fc_mu = nn.Linear(n_features, self.latent_dim)
        self.fc_logvar = nn.Linear(n_features, self.latent_dim)

        self.fc_decode = nn.Linear(self.latent_dim, n_features)
        decoder_layers = []
        reversed_widths = widths[::-1]
        for in_ch, out_ch in zip(reversed_widths[:-1], reversed_widths[1:]):
            decoder_layers += [
                nn.ConvTranspose2d(in_ch, out_ch, kernel_size=4, stride=2, padding=1),
                nn.BatchNorm2d(out_ch),
                nn.ReLU(inplace=True),
            ]
        decoder_layers += [
            nn.ConvTranspose2d(
                reversed_widths[-1], channels, kernel_size=4, stride=2, padding=1
            ),
            nn.Tanh(),  # images are scaled to [-1, 1]
        ]
        self.decoder = nn.Sequential(*decoder_layers)

    def encode(self, x):
        """Return (mu, logvar) of the approximate posterior q(z|x)."""
        h = self.encoder(x).flatten(start_dim=1)
        return self.fc_mu(h), self.fc_logvar(h)

    @staticmethod
    def reparameterize(mu, logvar):
        """Sample z = mu + sigma * eps in a way gradients can flow through."""
        std = torch.exp(0.5 * logvar)
        return mu + std * torch.randn_like(std)

    def decode(self, z):
        h = self.fc_decode(z).view(z.size(0), *self.feature_shape)
        return self.decoder(h)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        return self.decode(z), mu, logvar


def vae_loss_terms(recon, x, mu, logvar, recon_loss="mse"):
    """Return (reconstruction, KL) terms, each summed per image then averaged."""
    if recon_loss == "mse":
        per_pixel = F.mse_loss(recon, x, reduction="none")
    elif recon_loss == "l1":
        per_pixel = F.l1_loss(recon, x, reduction="none")
    else:
        raise ValueError(f"recon_loss must be 'mse' or 'l1'; got {recon_loss!r}")
    recon_term = per_pixel.flatten(start_dim=1).sum(dim=1).mean()
    kl_term = (-0.5 * (1.0 + logvar - mu.pow(2) - logvar.exp()).sum(dim=1)).mean()
    return recon_term, kl_term


class VAELitModule(GenerativeLitModule):
    """LightningModule for training/sampling the ConvVAE.

    Architecture args (image_shape, latent_dim, base_channels, channel_mults)
    come from model_arch_params; the rest from training_params.

    kl_weight is the "beta" of beta-VAE: 1.0 is the standard VAE objective;
    smaller values give sharper reconstructions but a latent distribution
    further from N(0, I) (so worse samples), larger values the reverse.
    kl_warmup_epochs linearly ramps the KL weight from 0, which helps avoid
    posterior collapse early in training.
    """

    def __init__(
        self,
        image_shape=(64, 64, 3),
        latent_dim=128,
        base_channels=64,
        channel_mults=(1, 2, 4, 8),
        learning_rate=1e-3,
        kl_weight=1.0,
        kl_warmup_epochs=0,
        recon_loss="mse",
        weight_decay=0.0,
    ):
        super().__init__()
        self.vae = ConvVAE(
            image_shape=image_shape,
            latent_dim=latent_dim,
            base_channels=base_channels,
            channel_mults=channel_mults,
        )
        self.latent_dim = int(latent_dim)
        self.learning_rate = learning_rate
        self.kl_weight = float(kl_weight)
        self.kl_warmup_epochs = int(kl_warmup_epochs)
        self.recon_loss = recon_loss
        self.weight_decay = float(weight_decay)

    def forward(self, x):
        return self.vae(x)

    def current_kl_weight(self):
        if self.kl_warmup_epochs <= 0:
            return self.kl_weight
        ramp = min(1.0, (self.current_epoch + 1) / self.kl_warmup_epochs)
        return self.kl_weight * ramp

    def training_step(self, batch, batch_idx):
        x = batch
        recon, mu, logvar = self.vae(x)
        recon_term, kl_term = vae_loss_terms(recon, x, mu, logvar, self.recon_loss)
        loss = recon_term + self.current_kl_weight() * kl_term
        log_kwargs = dict(on_step=False, on_epoch=True, batch_size=x.size(0))
        self.log("loss", loss, prog_bar=True, **log_kwargs)
        self.log("recon_loss", recon_term, **log_kwargs)
        self.log("kl_loss", kl_term, **log_kwargs)
        return loss

    def configure_optimizers(self):
        optimizer = torch.optim.Adam(
            self.parameters(),
            lr=initial_learning_rate(self.learning_rate),
            weight_decay=self.weight_decay,
        )
        return optimizer_config(optimizer, self.learning_rate)

    # -- sampling interface -------------------------------------------------

    def make_noise(self, n, generator=None):
        return torch.randn(n, self.latent_dim, generator=generator)

    def sample_from_noise(self, noise):
        return self.vae.decode(noise)

    @torch.no_grad()
    def reconstruct(self, x):
        """Encode images and decode the posterior means (no sampling noise)."""
        was_training = self.training
        self.eval()
        try:
            mu, _ = self.vae.encode(x.to(self.device))
            return self.vae.decode(mu).clamp(-1.0, 1.0).cpu()
        finally:
            self.train(was_training)
